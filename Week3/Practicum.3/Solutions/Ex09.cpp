/*
Задача 9: Въвеждат се две цели положителни числа m - брой редове, и n - брой символи. На редовете с нечетен номер
се печатат
n тирета, а на редовете с четен номер - n звездички. Всеки ред започва и завършва със символа |.

Вход: 4 6
Изход:
|------|
|******|
|------|
|******|
*/

#include <iostream>

int main()
{
	int m, n;
	std::cin >> m >> n;

	for (int row = 1; row <= m; row++)
	{
		char symbol = (row % 2 == 1) ? '-' : '*';

		std::cout << '|';
		for (int i = 0; i < n; i++)
		{
			std::cout << symbol;
		}
		std::cout << "|\n";
	}
}
