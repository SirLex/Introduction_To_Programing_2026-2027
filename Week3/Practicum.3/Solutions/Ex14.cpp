/*
Задача 14: Разполагаме с B1 монети от 1 евро, B2 монети от 2 евро и B5 банкноти от 5 евро. Въвеждат се
последователно B1, B2,
B5 и сума P. Да се изведат всички начини, по които сумата P може да се изплати с наличните монети и банкноти. Всеки
начин се извежда на отделен ред като брой монети от 1 евро, брой монети от 2 евро и брой банкноти от 5 евро.
Начините да са подредени във възходящ ред по броя монети от 1 евро. Ако няма нито един начин, да се изведе No ways.

Вход: 3 5 2 18
Изход:
0 4 2
2 3 2
3 5 1
*/

#include <iostream>

int main()
{
	int b1, b2, b5, sum;
	std::cin >> b1 >> b2 >> b5 >> sum;

	bool hasWay = false;

	// избираме броя монети от 1 и 2 евро, а банкнотите от 5 евро се определят от остатъка
	for (int ones = 0; ones <= b1; ones++)
	{
		for (int twos = 0; twos <= b2; twos++)
		{
			int rest = sum - ones - 2 * twos;

			// остатъкът трябва да може да се изплати само с банкноти от 5 евро
			if (rest < 0 || rest % 5 != 0)
			{
				continue;
			}

			int fives = rest / 5;

			if (fives > b5)
			{
				continue;
			}

			std::cout << ones << ' ' << twos << ' ' << fives << '\n';
			hasWay = true;
		}
	}

	if (!hasWay)
	{
		std::cout << "No ways\n";
	}
}
