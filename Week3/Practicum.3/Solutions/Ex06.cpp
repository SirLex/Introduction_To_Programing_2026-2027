/*
Задача 6: Въвеждат се неотрицателно цяло число и една цифра. Да се изведе колко пъти цифрата се среща в записа на
числото.

Вход: 77517 7, Изход: 3

Вход: 0 0, Изход: 1
*/

#include <iostream>

int main()
{
	int number, digit;
	std::cin >> number >> digit;

	int count = 0;

	// do-while, за да се провери поне една цифра - иначе при числото 0
	// цикълът не би се изпълнил и цифрата 0 нямаше да бъде преброена
	do
	{
		if (number % 10 == digit)
		{
			count++;
		}
		number /= 10;
	} while (number > 0);

	std::cout << count;
}
