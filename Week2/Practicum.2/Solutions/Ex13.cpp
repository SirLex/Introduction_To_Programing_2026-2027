/*
Задача 13: Въвеждат се неотрицателни цели числа, докато не се въведе отрицателно число. Отрицателното число служи
само за край и не е част от редицата. Да се изведе поредният номер на най-малкото въведено число, като номерацията
започва от 1. Ако най-малкото число се среща няколко пъти, да се изведе номерът на последното му срещане.
Гарантирано е, че преди отрицателното число е въведено поне едно число.

Вход: 5 3 8 3 9 -1, Изход: 4

Вход: 7 -5, Изход: 1
*/

#include <iostream>

int main()
{
	int number;
	std::cin >> number;

	// първото число е най-малкото до момента
	int minNumber = number;
	int minPosition = 1;
	int position = 1;

	std::cin >> number;

	while (number >= 0)
	{
		position++;

		// <= вместо <, за да запомним последното срещане при равни стойности
		if (number <= minNumber)
		{
			minNumber = number;
			minPosition = position;
		}

		std::cin >> number;
	}

	std::cout << minPosition;
}
