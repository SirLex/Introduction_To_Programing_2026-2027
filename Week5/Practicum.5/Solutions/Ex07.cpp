/*
Задача 7: Да се изведе индексът на най-десния елемент на масива, който е по-голям от средноаритметичното на двата
си съседа. Първият и последният елемент не се разглеждат, тъй като имат само по един съсед. Ако няма такъв елемент,
да се изведе -1.

Вход:
9
1 4 9 20 2 5 11 2 70

Изход:
6

Вход:
4
1 1 1 1

Изход:
-1
*/

#include <iostream>

int main()
{
	const int MAX_SIZE = 100;

	int arr[MAX_SIZE];
	int n;
	std::cin >> n;

	for (int i = 0; i < n; i++)
	{
		std::cin >> arr[i];
	}

	int result = -1;

	// търсим отдясно наляво, затова първият намерен е най-десният
	for (int i = n - 2; i >= 1; i--)
	{
		// arr[i] > (arr[i - 1] + arr[i + 1]) / 2, умножено по 2,
		// за да сравняваме цели числа и да избегнем деленето
		if (2 * arr[i] > arr[i - 1] + arr[i + 1])
		{
			result = i;
			break;
		}
	}

	std::cout << result;
}
