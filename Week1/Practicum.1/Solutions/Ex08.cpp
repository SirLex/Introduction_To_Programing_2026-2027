/*
Задача 8: Въвеждат се 4 цели числа. Да се изведе сумата на четните измежду тях.

Вход: 17 4 63 78, Изход: 82
*/

#include <iostream>

int main()
{
	int a, b, c, d;
	std::cin >> a >> b >> c >> d;

	int sum = a * (a % 2 == 0)
		+ b * (b % 2 == 0)
		+ c * (c % 2 == 0)
		+ d * (d % 2 == 0);

	std::cout << sum;
}